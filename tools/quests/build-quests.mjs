// Builds EncoreEssentials_DB/Data/Quests-<source>.lua: each instance's quests and the quest chains they belong to.
// Usage: node tools/quests/build-quests.mjs [--source questie,fillin]
//
// The data comes from quest sources in tools/quests/sources/. Each source turns one database into the same
// source-neutral model (see tools/quests/README.md), and this file writes that model as Lua, one file per source.
// The addon's quest data layer (EncoreEssentials_DB/QuestData.lua) merges them by priority, so a later source only
// fills what an earlier one left blank. Default order (project rule, 2026-11-19): QuestieDB, then Wowhead Forever.
// To move to another database, add a source and pass --source <ids>; the addon's code does not change.
// Every file a source writes must also be listed in EncoreEssentials_DB.toc.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeJson } from '../loot/net.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const DATA = path.join(ROOT, 'EncoreEssentials_DB', 'Data');

const arg = (name, def) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : def; };
const sourceIds = arg('--source', 'questie,fillin').split(',').map((x) => x.trim()).filter(Boolean);
for (const id of sourceIds) if (!/^[a-z0-9-]+$/.test(id)) throw new Error(`bad source name: ${id}`);

const qn = (s) => (s == null ? 'nil' : q(s));
const q = (s) => JSON.stringify(String(s)).replace(/\\u([0-9a-f]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
const n = (v) => String(Math.round(v * 10) / 10);
function who(w) {
  if (!w) return null;
  const parts = [q(w.kind), w.id, w.name ? q(w.name) : 'nil'];
  if (w.map) parts.push(w.map, n(w.x), n(w.y));
  return `{ ${parts.join(', ')} }`;
}
const list = (a) => `{ ${a.join(', ')} }`;
const items = (a) => list(a.map(([i, c]) => (c > 1 ? `{ ${i}, ${c} }` : String(i))));


// Sources run in order; each sees the quest IDs the ones before it found (a fill-in source needs them).
const ctx = { questIds: new Set() };
const reports = [];
for (const sourceId of sourceIds) {
  const source = await import(`./sources/${sourceId}.mjs`);
  const model = await source.load(ctx);
  model.source.priority ??= source.priority ?? 0;
  const OUT = path.join(DATA, `Quests-${model.source.id}.lua`);
  const L = [];
  if (model.source.header) L.push(model.source.header);
  L.push(`-- Encore-DB dungeon quests. Generated by tools/quests/build-quests.mjs --source ${model.source.id}: do not edit by hand.`);
  L.push(`-- ${model.source.credit || 'Quest details'}, data version ${model.source.version}${model.source.build ? `, WoW Forever build ${model.source.build}` : ''}.`);
  L.push('-- Licence and credit: see NOTICE.txt in this addon.');
  L.push(`-- Built ${new Date().toISOString().slice(0, 10)}.`);
  L.push('local _, ns = ...');
  L.push('ns.QuestSources = ns.QuestSources or {}');
  L.push('table.insert(ns.QuestSources, {');
  L.push(`  id = ${q(model.source.id)}, name = ${q(model.source.name)}, url = ${qn(model.source.url)},`);
  L.push(`  credit = ${qn(model.source.credit)}, version = ${q(model.source.version)}, priority = ${model.source.priority || 0},`);
  L.push('  -- [instance key] = its quests (instance keys are the instance name in lower case, as in Loot.lua)');
  L.push('  instances = {');
  for (const I of [...model.instances].sort((a, b) => a.key.localeCompare(b.key))) {
    L.push(`    [${q(I.key)}] = ${list(I.quests)}, -- ${I.name}`);
  }
  L.push('  },');
  L.push('  -- [quest] = { title, level, minLevel, side ("A"/"H", nil = both or unknown), objective, text, start, finish,');
  L.push('  --   prev, next (quests before and after it), xp, money (copper), rewards, choice (item, or { item, count }), new,');
  L.push('  --   rewardItems (reward items not split into given and choice), rep ({ faction, amount } reputation rewards) }');
  L.push('  -- start, finish: { kind ("npc", "object", "item"), id, name, map (uiMap), x, y }');
  L.push('  quests = {');
  for (const id of Object.keys(model.quests).map(Number).sort((a, b) => a - b)) {
    const Q = model.quests[id];
    const f = [];
    if (Q.title) f.push(`title = ${q(Q.title)}`);
    if (Q.level) f.push(`level = ${Q.level}`);
    if (Q.minLevel) f.push(`minLevel = ${Q.minLevel}`);
    if (Q.side) f.push(`side = ${q(Q.side)}`);
    if (Q.isNew) f.push('new = true');
    if (Q.objective) f.push(`objective = ${q(Q.objective)}`);
    if (Q.text) f.push(`text = ${q(Q.text)}`);
    if (Q.start) f.push(`start = ${who(Q.start)}`);
    if (Q.finish) f.push(`finish = ${who(Q.finish)}`);
    if (Q.prev?.length) f.push(`prev = ${list(Q.prev)}`);
    if (Q.next?.length) f.push(`next = ${list(Q.next)}`);
    if (Q.xp) f.push(`xp = ${Q.xp}`);
    if (Q.money) f.push(`money = ${Q.money}`);
    if (Q.rewards?.length) f.push(`rewards = ${items(Q.rewards)}`);
    if (Q.choice?.length) f.push(`choice = ${items(Q.choice)}`);
    if (Q.rewardItems?.length) f.push(`rewardItems = ${list(Q.rewardItems)}`);
    if (Q.rep?.length) f.push(`rep = { ${Q.rep.map(([fa, v]) => `{ ${fa}, ${v} }`).join(', ')} }`);
    L.push(`    [${id}] = { ${f.join(', ')} },`);
  }
  L.push('  },');
  L.push('  -- [item] = { name, quality }: reward names until the game has the item');
  L.push('  items = {');
  for (const id of Object.keys(model.items).map(Number).sort((a, b) => a - b)) {
    const [name, quality] = model.items[id];
    L.push(`    [${id}] = { ${q(name)}${quality != null ? `, ${quality}` : ''} },`);
  }
  L.push('  },');
  L.push('})');
  fs.writeFileSync(OUT, L.join('\n') + '\n');
  for (const id of Object.keys(model.quests)) ctx.questIds.add(Number(id));
  // The IDs to collect from Wowhead Forever (tools/refresh.mjs builds its browser job list from this).
  writeJson('out/quest-ids.json', [...ctx.questIds].sort((a, b) => a - b));
  const report = {
    source: model.source,
    instances: model.instances.map((I) => ({ key: I.key, name: I.name, quests: I.quests.length })),
    quests: Object.keys(model.quests).length,
    untitled: Object.values(model.quests).filter((Q) => !Q.title).map((Q) => Q.id),
    left: model.left,
  };
  reports.push(report);
  console.log(`${path.relative(ROOT, OUT)}: ${report.instances.length} instances, ${report.quests} quests`);
}
const rp = writeJson('out/quests-report.json', reports);
console.log(`report -> ${path.relative(ROOT, rp)}`);
