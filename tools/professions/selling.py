#!/usr/bin/env python3
"""Builds EncoreEssentials_Professions/Data/Selling.lua: the Waylaid Crates and Craftsman's Writs of WoW Forever.

    python3 tools/professions/selling.py

Inputs (read from Wowhead Forever, https://www.wowhead.com/forever, on 2026-11-26):
- selling/crates.tsv: crate item, rank, kind, and the bundles that fill it ("count item name; ...").
  Item tooltips "Fill the crate with any bundle from the following list" (items 248682-248713).
- selling/writs.tsv: profession, writ item, the item to deliver (name, item), the NPC who takes it ("-" when
  Wowhead has none), their zone, and the tier (J, E, A). From Wowhead Forever's Craftsman's Writs guide
  (guide=35185) and the writ items.
The Season of Discovery "Waylaid Supplies" items are still in the game files but Wowhead marks them unconfirmed,
so they are left out.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "EncoreEssentials_Professions", "Data", "Selling.lua")

RANKS = {"Apprentice": 1, "Journeyman": 2, "Expert": 3, "Artisan": 4}
TIERS = {"J": 2, "E": 3, "A": 4}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rows(name):
    with open(os.path.join(HERE, "selling", name), encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.strip():
                yield line.split("\t")


def main():
    out = [
        "-- Encore-Professions data. Generated by tools/professions/selling.py: do not edit by hand.",
        "-- Waylaid Crates and Craftsman's Writs of WoW Forever, read from Wowhead Forever",
        "-- (https://www.wowhead.com/forever) on 2026-11-26. Coin Pouch averages: Wowhead Forever's looter data.",
        "-- Merchant's Favor per crate: player reports (about 10, 20, 30 and 40 by rank).",
        "-- Licence: GPL-3.0; see NOTICE.txt in this addon.",
        "local _, ns = ...",
        "",
        "-- rank 1 Apprentice, 2 Journeyman, 3 Expert, 4 Artisan",
        "ns.SellRanks = { \"Apprentice\", \"Journeyman\", \"Expert\", \"Artisan\" }",
        "-- Merchant's Favor for a filled crate, by rank.",
        "ns.CrateFavor = { 10, 20, 30, 40 }",
        "-- Craftsman's Writs by rank (2 Journeyman, 3 Expert, 4 Artisan): reputation, and the Coin Pouch's average",
        "-- in copper (Wowhead Forever's looter: about 12 silver, 36 silver and 74 silver 56 copper).",
        "ns.WritRep = { [2] = 75, [3] = 125, [4] = 200 }",
        "ns.WritPouch = { [2] = 1200, [3] = 3600, [4] = 7456 }",
        "",
        "-- { crate item, rank, kind, { item, count, ... } }: any one bundle fills the crate.",
        "ns.Crates = {",
    ]
    for crate, rank, kind, bundles in rows("crates.tsv"):
        parts = []
        for b in bundles.split(";"):
            n, item, _name = b.strip().split(" ", 2)
            parts += [item, n]
        out.append("  { %s, %d, %s, { %s } }," % (crate, RANKS[rank], lua_str(kind), ", ".join(parts)))
    out += ["}", "",
            "-- { writ item, profession, item to deliver, its name, NPC (or false), zone, rank }",
            "ns.Writs = {"]
    for prof, writ, name, item, npc, zone, tier in rows("writs.tsv"):
        out.append("  { %s, %s, %s, %s, %s, %s, %d }," % (
            writ, lua_str(prof), item, lua_str(name), "false" if npc == "-" else lua_str(npc), lua_str(zone),
            TIERS[tier]))
    out += ["}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
